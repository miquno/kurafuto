#!/usr/bin/env swift
// Renders the app icon from the pixel map below. Each cell becomes a 32×32 px block of an opaque
// 1024×1024 PNG, so the pixel art stays sharp. Edit the map or the palette, then run:
//   swift scripts/make-app-icon.swift Kurafuto/Resources/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png
import CoreGraphics
import Foundation
import ImageIO
import UniformTypeIdentifiers

let map = """
................................
................................
................................
....HHHHHHHHHHHHHHHHHHHHHHHH....
....HFFFFFFFFFFFFFFFFFFFFFFS....
....HFWWWWWWWWWWWWWWWWWWWWFS....
....HFWUUUUUUUUUUUUbbbbUUUFS....
....HFWUvUvUvUvUvUUblLbkkUFS....
....HFWUvUvUvUvUvUUbLLbkkUFS....
....HFWUUUUUUUUUUUUbbbbUUUFS....
....HFDDDDDDDDDDDDDDDDDDDDFS....
....HFggggggggggggggggggggFS....
....HFWWWWWWWWWWWWWWWWWWWWFS....
....HFWUUUUUUUUUUUUbbbbUUUFS....
....HFWUvUvUvUvUvUUblLbkkUFS....
....HFWUvUvUvUvUvUUbLLbkkUFS....
....HFWUUUUUUUUUUUUbbbbUUUFS....
....HFDDDDDDDDDDDDDDDDDDDDFS....
....HFggggggggggggggggggggFS....
....HFWWWWWWWWWWWWWWWWWWWWFS....
....HFWUUUUUUUUUUUUbbbbUUUFS....
....HFWUvUvUvUvUvUUblLbkkUFS....
....HFWUvUvUvUvUvUUbLLbkkUFS....
....HFWUUUUUUUUUUUUbbbbUUUFS....
....HFDDDDDDDDDDDDDDDDDDDDFS....
....HFPPPPPPPPPPPPPPbbbbPPFS....
....HFPPgPgPgPgPgPPPblLbPPFS....
....HFPPPPPPPPPPPPPPbbbbPPFS....
....SSSSSSSSSSSSSSSSSSSSSSSS....
......SSS..............SSS......
................................
................................
"""

let palette: [Character: UInt32] = [
    ".": 0x0C1428, // background
    "H": 0x4A5F86, // frame highlight
    "F": 0x2E3D5C, // frame
    "S": 0x1C2740, // frame shadow, feet
    "g": 0x141B2E, // gap between units
    "W": 0xDCE3EE, // unit highlight
    "U": 0xB8C2D3, // unit face
    "D": 0x8692A8, // unit shadow
    "v": 0x2A3550, // vent holes
    "b": 0x3A4866, // LED bezel
    "L": 0x39D873, // status LED
    "l": 0xB4FFD0, // LED glint
    "k": 0x6B7890, // button
    "P": 0x24304A, // bottom panel
]

let rows = map.split(separator: "\n").map(Array.init)
let cells = rows.count
let size = 1024
let cell = size / cells
guard rows.allSatisfy({ $0.count == cells }), cell * cells == size else {
    fatalError("pixel map must be square and divide 1024 evenly")
}
guard CommandLine.arguments.count == 2 else { fatalError("usage: make-app-icon.swift <output.png>") }

guard let ctx = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: 0,
                          space: CGColorSpace(name: CGColorSpace.sRGB)!,
                          bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue) else { fatalError("no context") }
for (y, row) in rows.enumerated() {
    for (x, char) in row.enumerated() {
        guard let hex = palette[char] else { fatalError("unknown pixel '\(char)' at \(x),\(y)") }
        ctx.setFillColor(red: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255,
                         blue: CGFloat(hex & 0xFF) / 255, alpha: 1)
        // CoreGraphics' origin is bottom-left; the map reads top to bottom.
        ctx.fill(CGRect(x: x * cell, y: size - (y + 1) * cell, width: cell, height: cell))
    }
}

let url = URL(fileURLWithPath: CommandLine.arguments[1])
guard let image = ctx.makeImage(),
      let dest = CGImageDestinationCreateWithURL(url as CFURL, UTType.png.identifier as CFString, 1, nil) else {
    fatalError("cannot write \(url.path)")
}
CGImageDestinationAddImage(dest, image, nil)
guard CGImageDestinationFinalize(dest) else { fatalError("cannot write \(url.path)") }
print("wrote \(url.path)")
